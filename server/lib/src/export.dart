import 'package:meets_core/meets_core.dart';

String _md(String s) => s.replaceAll('|', '\\|').replaceAll('\n', ' ');

/// The kit as a Markdown document, ready for a doc, deck notes or an email.
String kitMarkdown(CompKit kit, {String? url}) {
  final b = kit.brief;
  final f = b.format;
  final out = StringBuffer();
  out.writeln('# ${b.title.isEmpty ? 'Comp kit' : b.title} — comp kit');
  out.writeln();
  out.writeln('*${f.label} · ${b.marketInfo.name} · generated by Meets from Qloo taste data on ${kit.createdAt.toIso8601String().substring(0, 10)}'
      '${kit.mode == 'preview' ? ' · PREVIEW DATA, NOT FROM QLOO' : ''}*');
  if (url != null) out.writeln('\n$url');
  out.writeln();
  if (kit.headline != null) out.writeln('> ${kit.headline}\n');
  if (kit.summary != null) out.writeln('${kit.summary}\n');

  out.writeln('## Touchstones');
  for (final a in kit.anchors) {
    out.writeln('- ${a.name} (${a.kind.label}${a.year == null ? '' : ', ${a.year}'})');
  }
  out.writeln();

  out.writeln('## Comps (${f.primary.plural.toLowerCase()})');
  out.writeln('| Title | Year | Creator | Fit | Size | Notes |');
  out.writeln('|---|---|---|---|---|---|');
  for (final c in kit.primary.items.take(15)) {
    final e = c.entity;
    out.writeln('| ${_md(e.name)} | ${e.year ?? ''} | ${_md(e.creator ?? '')} | ${(c.fit * 100).round()} | '
        '${c.size.label} (${topPercentLabel(e.popularity)}) | ${c.isSweetSpot ? 'Sweet spot' : c.flags.map(flagLabel).join(', ')} |');
  }
  if (kit.primary.filters.isNotEmpty) out.writeln('\nFilters: ${kit.primary.filters.join('; ')}.');
  out.writeln();

  if (kit.compCheck.isNotEmpty) {
    out.writeln('## Your comps, checked');
    for (final v in kit.compCheck) {
      out.writeln('- **${v.input}** — ${v.verdict == 'keep' ? 'keep' : v.verdict == 'swap' ? 'swap' : 'not found'}. ${v.reasons.join(' ')}'
          '${v.swap == null ? '' : ' Try: ${v.swap!.entity.name}.'}');
    }
    out.writeln();
  }

  out.writeln('## Pitch copy');
  for (final c in kit.copy) {
    out.writeln('### ${c.title}\n\n${c.body}\n');
  }

  out.writeln('## The audience');
  final audience = kit.audience;
  if (audience != null && !audience.isEmpty) {
    out.writeln(describeAudience(audience, f.audience));
    if (audience.descriptors.isNotEmpty) out.writeln('\nTaste descriptors: ${audience.descriptors.map((t) => t.name).join(', ')}.');
  }
  for (final scan in kit.cross) {
    out.writeln('\n**They also ${scan.kind.consumeVerb}:** ${scan.items.take(6).map((c) => c.entity.name).join(', ')}');
  }
  if (kit.markets.isNotEmpty) {
    out.writeln('\n**Markets:** ${kit.markets.map((m) => '${m.name}${m.label == 'hidden_gem' ? ' (hidden gem)' : ''}').join(', ')}');
  }
  out.writeln();

  out.writeln('## Targeting lists');
  for (final t in kit.targeting) {
    out.writeln('### ${t.platform}\n\n${t.how}\n');
    for (final item in t.items) {
      out.writeln('- $item');
    }
    out.writeln();
  }

  if (kit.notes.isNotEmpty) {
    out.writeln('## Notes');
    for (final n in kit.notes) {
      out.writeln('- $n');
    }
  }
  return out.toString();
}

String _csv(String? s) {
  final v = s ?? '';
  return v.contains(RegExp(r'[",\n]')) ? '"${v.replaceAll('"', '""')}"' : v;
}

/// Every candidate in the kit as CSV, for spreadsheets and ad tools.
String kitCsv(CompKit kit) {
  final rows = <String>['section,category,name,creator,year,fit,qloo_affinity,qloo_popularity,size,flags,qloo_id'];
  for (final scan in [kit.primary, ...kit.cross, ...kit.channels]) {
    for (final c in scan.items) {
      final e = c.entity;
      rows.add([
        scan.role,
        scan.kind.label,
        _csv(e.name),
        _csv(e.creator),
        '${e.year ?? ''}',
        c.fit.toStringAsFixed(3),
        e.affinity?.toStringAsFixed(4) ?? '',
        e.popularity?.toStringAsFixed(6) ?? '',
        c.size.label,
        _csv(c.flags.join(' ')),
        e.id,
      ].join(','));
    }
  }
  return '${rows.join('\n')}\n';
}
